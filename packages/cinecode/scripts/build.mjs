import { execFileSync } from "node:child_process";
import { chmodSync, cpSync, existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";
import { assertBuildOutput } from "../../../scripts/assert-output.mjs";

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const distDir = path.join(pkgDir, "dist");
const emitDir = path.join(distDir, "esm");
const versionFile = path.join(pkgDir, "src", "version.generated.ts");
const startedAt = Date.now();

const manifest = JSON.parse(readFileSync(path.join(pkgDir, "package.json"), "utf8"));
if (typeof manifest.version !== "string" || manifest.version === "") {
  console.error("build failed: package.json has no version");
  process.exit(1);
}

rmSync(distDir, { recursive: true, force: true });
writeFileSync(
  versionFile,
  `// Generated by scripts/build.mjs from package.json. Do not edit.\nexport const BUILD_VERSION: string = ${JSON.stringify(manifest.version)};\n`,
);

const tsc = createRequire(path.join(pkgDir, "package.json")).resolve("typescript/bin/tsc");
execFileSync(process.execPath, [tsc, "-p", "tsconfig.build.json"], { cwd: pkgDir, stdio: "inherit" });

const binEntries = Object.values(manifest.bin ?? {}).map((entry) => path.resolve(pkgDir, entry));
if (process.platform !== "win32") {
  for (const entry of binEntries) chmodSync(entry, 0o755);
}

const staticSrc = path.join(pkgDir, "src", "dev", "static");
if (existsSync(staticSrc)) {
  cpSync(staticSrc, path.join(distDir, "viewer"), { recursive: true });
}

// Generate JSON Schema from authoring Zod schema at build time
const { generateSchemaJson } = await import(pathToFileURL(path.join(emitDir, "config", "json-schema.js")).href);
writeFileSync(path.join(pkgDir, "cinecode.schema.json"), generateSchemaJson());

try {
  const result = assertBuildOutput({ packageDir: pkgDir, emitDir, binEntries });
  const seconds = ((Date.now() - startedAt) / 1000).toFixed(1);
  console.log(
    `build ok: ${result.scripts} scripts, ${result.declarations} declarations, ${result.bins} bin, ${result.files} files in ${seconds}s`,
  );
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
